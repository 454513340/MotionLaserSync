#include "twin/ScanReplayAdapter.h"
#include "twin/VirtualLaser2950.h"
#include "twin/MultiPosePlayback.h"
#include "twin/MultiPoseNcSimulation.h"
#include "twin/MultiPoseCloudComparison.h"
#include <QVector>
#include <QVector3D>
#include <QString>
#include <array>
#include <atomic>
#include <memory>

namespace mls::twin {
struct MultiPoseQtReport {
    ExperimentPlan plan;
    ConnectedExperimentSession connectedSession; // the ONLY source for continuous all-pose NC
    QString continuousSessionIssue;
    ExperimentOptions options;
    Pose6 cadPose{};
    QString cadPath,scanPath,kinematicsSummary,warning,status;
    // Immutable identities of loaded candidate data, NOT site acceptance.
    QString cadSha256, realScanSha256, partPoseId, calibrationId, physical17Sha256;
    bool physical17ReplayConsistent=false;
    bool rotaryReplayExcited=false;
    bool machineCollisionModelLoaded=false;
    bool opticalPreviewUsable=false; // every requested pose has at least one CAD hit
    std::size_t timeOrderAnomalies=0;
    std::array<double,17> physicalParameters{};
    Transform physical17Anchor{}; // FK-to-archived-MCS mapping; for same-path replay
    QVector<QVector<QVector3D>> virtualPointPreviews;
    QVector<QVector<QVector<QVector3D>>> opticalPlaybackFrames;
    QVector<QVector<double>> opticalPlaybackTimes;
    QVector<QVector<QVector3D>> scanFocusPaths;
    QVector<QVector3D> transferFocusPath;
    QVector<int> previewProfilesWithWorkpieceHit;
    QVector<double> previewRoiCoverageFractions;
    QVector<double> previewBoundaryCoverageFractions;
    QVector<QString> previewCoverageWarnings;
    bool ok() const {return status.isEmpty()&&plan.ok();}
};
struct MultiPoseSimPoseArtifacts {
    QString poseId;
    QString plyPath;
    QString ncSha256;
    QString ncFilePath;
    QVector<QVector3D> comparisonPreview; // bounded observed workpiece points
    QVector<QVector<QVector3D>> replayFrames; // bounded optical samples per frame
    QVector<double> replayTimes;
    std::uint64_t validWorkpiecePoints=0;
    std::uint64_t profileCount=0;
};
struct MultiPoseSimArtifacts {
    QVector<MultiPoseSimPoseArtifacts> poses;
    QString directory,manifestPath,allPosesPlyPath;
};
struct MultiPoseCompareArtifacts {
    QString error,description,poseId,realScanPath;
    QVector<QVector3D> realPoints;
    QVector<float> realDistancesMm;
    MultiPoseCloudMetrics metrics;
    bool ok() const {return error.isEmpty()&&metrics.valid;}
};
struct MultiPoseOfflineNcRun {
    std::string text;
    NcSimResult execution;
    QString error;
    bool ok() const {return error.isEmpty()&&execution.ok();}
};
class MultiPoseExperimentQtAdapter {
public:
    static std::shared_ptr<MultiPoseQtReport> planAndSimulatePreview(
        const TwinScene& scene,const ScanReplayData& real,
        const std::vector<ExperimentPose>& orientations,
        const ExperimentOptions& options,const Sensor2950Geometry& optical,
        const QString& machineConfigPath,const std::atomic<bool>* cancel=nullptr);
    // Executable source of truth: NC text generated by the same exporter,
    // strictly parsed and compared with planner XYZCB/time/capture segments.
    static MultiPoseOfflineNcRun executeNcForPose(const MultiPoseQtReport& report,
        std::size_t index,int topology,int h3Edge=115,
        const std::string* exactNcText=nullptr);
    static MultiPoseOfflineNcRun executeConnectedNc(const MultiPoseQtReport& report,
        int topology,int h3Edge=115,
        const std::string* exactNcText=nullptr);
    static MultiPosePlaybackState replayConnectedNcAt(const MultiPoseQtReport& report,
        const NcSimResult& nc,const MultiPosePlaybackTimeline& timeline,double time);
    static MultiPosePlaybackState replayStateAt(const MultiPoseQtReport& report,
        const std::vector<NcSimResult>& executedNc,
        const MultiPosePlaybackTimeline& timeline,double globalTime);
    static MultiPoseCompareArtifacts compareRealScanForPose(
        const MultiPoseQtReport& plan,const MultiPoseSimArtifacts& simulation,
        std::size_t poseIndex,const QString& realScanFile,double toleranceMm=0.25);
    static QString exportOfflineNcAndManifest(const MultiPoseQtReport& report,
        const QString& directory,int h3LatchEdge=115,
        const std::vector<std::string>* exactSelectedNc=nullptr,
        int selectedTopology=0,
        const std::string* verifiedConnectedNc=nullptr);
    // CPU-intensive explicit user action: fully simulate every planned profile.
    // Produces SCAN-v3 PoseTiming::Simulated, NEVER real measurement evidence.
    static QString exportSimulatedProfilesForM3M4(const MultiPoseQtReport& report,
        const TwinScene& scene,const Sensor2950Geometry& optical,
        const QString& directory,const std::vector<std::string>& exactNcTexts,
        int topology,const std::atomic<bool>* cancel=nullptr,
        std::atomic<std::size_t>* completedProfiles=nullptr,
        MultiPoseSimArtifacts* artifacts=nullptr);
};
} // namespace mls::twin
